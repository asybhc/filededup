// Package corpusgen 生成固定 seed 的可复现测试语料。
//
// 设计约束：
//   - 同一 seed 两次生成的路径清单哈希（PathListSHA256）必须完全一致；
//   - 主语料在 Windows/macOS/Linux 上路径相同；平台不支持的场景（符号链接等）以普通文件降级，
//     路径不变、内容可能不同，因此另行记录 FileSetSHA256 与 Notes；
//   - 语料中的时间戳固定为 2024-01-01T00:00:00Z 起的确定性偏移（不进入清单哈希，各文件系统精度不同）；
//   - 生成器绝不删除"非自己生成"的目录（靠同级 .corpusgen 标记文件判定）。
package main

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"hash/fnv"
	"math/rand"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strings"
	"time"

	"golang.org/x/text/unicode/norm"
)

const (
	corpusSchemaVersion = 1
	markerSuffix        = ".corpusgen"
	manifestSuffix      = "-manifest.json"
	baseTime            = "2024-01-01T00:00:00Z"
)

// Entry 是语料中的一个条目。Path 使用 "/" 分隔且为 NFC 形式，保证跨平台可比。
type Entry struct {
	Path          string `json:"path"`
	Kind          string `json:"kind"` // dir | file | hardlink | symlink
	Size          int64  `json:"size"`
	SHA256        string `json:"sha256,omitempty"`
	LinkTarget    string `json:"linkTarget,omitempty"`
	HardlinkGroup string `json:"hardlinkGroup,omitempty"`
	Note          string `json:"note,omitempty"`
}

// Manifest 是语料清单。PathListSHA256 跨平台必须一致。
type Manifest struct {
	SchemaVersion  int      `json:"schemaVersion"`
	Seed           int64    `json:"seed"`
	Goos           string   `json:"goos"`
	PathListSHA256 string   `json:"pathListSHA256"`
	FileSetSHA256  string   `json:"fileSetSHA256"`
	Entries        []Entry  `json:"entries"`
	Notes          []string `json:"notes,omitempty"`
}

type generator struct {
	root    string
	seed    int64
	count   int
	entries []Entry
	dirSet  map[string]bool
	fileSet map[string]bool
	notes   []string
}

// Generate 在 outDir 生成语料并返回清单。outDir 必须为空或由本工具先前生成。
func Generate(outDir string, seed int64) (m *Manifest, err error) {
	defer func() {
		if r := recover(); r != nil {
			if e, ok := r.(error); ok {
				err = e
				return
			}
			err = fmt.Errorf("生成语料时发生异常: %v", r)
		}
	}()

	abs, absErr := filepath.Abs(outDir)
	if absErr != nil {
		return nil, absErr
	}
	if err := prepareDir(abs); err != nil {
		return nil, err
	}
	g := &generator{root: abs, seed: seed, dirSet: map[string]bool{}, fileSet: map[string]bool{}}
	if err := g.build(); err != nil {
		return nil, err
	}
	return g.finalize(), nil
}

func prepareDir(dir string) error {
	base := filepath.Base(dir)
	if base == "." || base == string(filepath.Separator) || strings.TrimSpace(base) == "" {
		return fmt.Errorf("拒绝在无效目录生成语料：%q", dir)
	}
	parent := filepath.Dir(dir)
	marker := filepath.Join(parent, base+markerSuffix)

	if st, err := os.Stat(dir); err == nil {
		if !st.IsDir() {
			return fmt.Errorf("目标不是目录：%s", dir)
		}
		ents, err := os.ReadDir(dir)
		if err != nil {
			return err
		}
		if len(ents) > 0 {
			if _, err := os.Stat(marker); err != nil {
				return fmt.Errorf("目录非空且没有 %s 标记，拒绝覆盖：%s", base+markerSuffix, dir)
			}
			if err := os.RemoveAll(dir); err != nil {
				return err
			}
		}
	} else if !os.IsNotExist(err) {
		return err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	return os.WriteFile(marker, []byte("generated by tools/corpusgen; safe to delete\n"), 0o644)
}

func (g *generator) path(rel string) string {
	return filepath.Join(g.root, filepath.FromSlash(rel))
}

func (g *generator) note(format string, args ...any) {
	g.notes = append(g.notes, fmt.Sprintf(format, args...))
}

// ensureDir 递归注册目录（含中间目录）。
func (g *generator) ensureDir(rel string) {
	rel = norm.NFC.String(strings.Trim(rel, "/"))
	if rel == "" || rel == "." || g.dirSet[rel] {
		return
	}
	if parent := path.Dir(rel); parent != "." && parent != "/" {
		g.ensureDir(parent)
	}
	_ = os.MkdirAll(g.path(rel), 0o755)
	g.dirSet[rel] = true
	g.entries = append(g.entries, Entry{Path: rel, Kind: "dir"})
}

func (g *generator) file(rel string, data []byte) {
	rel = norm.NFC.String(strings.Trim(rel, "/"))
	g.ensureDir(path.Dir(rel))
	p := g.path(rel)
	_ = os.WriteFile(p, data, 0o644)
	g.fileSet[rel] = true
	g.entries = append(g.entries, Entry{
		Path:   rel,
		Kind:   "file",
		Size:   int64(len(data)),
		SHA256: sha256Hex(data),
	})
	g.touch(p)
}

// touch 设置确定性 mtime；不进清单哈希（不同文件系统精度不同）。
func (g *generator) touch(p string) {
	t := mustParseBase().Add(time.Duration(g.count) * time.Minute)
	g.count++
	_ = os.Chtimes(p, t, t)
}

func mustParseBase() time.Time {
	t, err := time.Parse(time.RFC3339, baseTime)
	if err != nil {
		panic(err)
	}
	return t
}

func (g *generator) rngFor(rel string) *rand.Rand {
	h := fnv.New64a()
	_, _ = h.Write([]byte(rel))
	return rand.New(rand.NewSource(g.seed ^ int64(h.Sum64())))
}

func (g *generator) text(rel, content string) {
	g.file(rel, []byte(content))
}

func (g *generator) randomFile(rel string, n int) {
	r := g.rngFor(rel)
	buf := make([]byte, n)
	for i := range buf {
		buf[i] = byte(r.Intn(256))
	}
	g.file(rel, buf)
}

func (g *generator) hardlink(rel, targetRel string) {
	rel = norm.NFC.String(rel)
	targetRel = norm.NFC.String(targetRel)
	g.ensureDir(path.Dir(rel))
	if err := os.Link(g.path(targetRel), g.path(rel)); err != nil {
		// 跨设备/权限不支持时降级为普通文件，路径保持不变。
		data, readErr := os.ReadFile(g.path(targetRel))
		if readErr != nil {
			g.note("hardlink %s 失败且无法复制目标: %v", rel, err)
			return
		}
		g.file(rel, data)
		g.note("hardlink %s 不支持，已降级为普通文件: %v", rel, err)
		return
	}
	data, _ := os.ReadFile(g.path(targetRel))
	g.fileSet[rel] = true
	g.entries = append(g.entries, Entry{
		Path:          rel,
		Kind:          "hardlink",
		Size:          int64(len(data)),
		SHA256:        sha256Hex(data),
		LinkTarget:    targetRel,
		HardlinkGroup: "hl:" + targetRel,
	})
}

func (g *generator) symlink(rel, targetRel string) {
	rel = norm.NFC.String(rel)
	g.ensureDir(path.Dir(rel))
	if err := os.Symlink(filepath.FromSlash(targetRel), g.path(rel)); err != nil {
		// Windows 需开发者模式/管理员权限；降级为普通文件保持路径一致。
		data := []byte("symlink fallback: " + targetRel + "\n")
		_ = os.WriteFile(g.path(rel), data, 0o644)
		g.fileSet[rel] = true
		g.entries = append(g.entries, Entry{Path: rel, Kind: "file", Size: int64(len(data)), SHA256: sha256Hex(data), Note: "symlink_unsupported"})
		g.note("symlink %s -> %s 不支持，已降级为普通文件: %v", rel, targetRel, err)
		return
	}
	g.entries = append(g.entries, Entry{Path: rel, Kind: "symlink", LinkTarget: targetRel})
}

// finalize 排序并计算两个哈希。
func (g *generator) finalize() *Manifest {
	sort.Slice(g.entries, func(i, j int) bool { return g.entries[i].Path < g.entries[j].Path })

	var pathBuf, setBuf strings.Builder
	for i, e := range g.entries {
		if i > 0 {
			pathBuf.WriteByte('\n')
		}
		pathBuf.WriteString(e.Path)
		fmt.Fprintf(&setBuf, "%s\t%s\t%d\t%s\t%s\t%s\n", e.Path, e.Kind, e.Size, e.SHA256, e.LinkTarget, e.HardlinkGroup)
	}
	return &Manifest{
		SchemaVersion:  corpusSchemaVersion,
		Seed:           g.seed,
		Goos:           goos(),
		PathListSHA256: sha256Hex([]byte(pathBuf.String())),
		FileSetSHA256:  sha256Hex([]byte(setBuf.String())),
		Entries:        g.entries,
		Notes:          g.notes,
	}
}

func sha256Hex(b []byte) string {
	s := sha256.Sum256(b)
	return hex.EncodeToString(s[:])
}

// WriteManifest 把清单写到语料目录的同级文件（避免污染被扫描的目录）。
func WriteManifest(corpusDir string, m *Manifest) (string, error) {
	abs, err := filepath.Abs(corpusDir)
	if err != nil {
		return "", err
	}
	p := filepath.Join(filepath.Dir(abs), filepath.Base(abs)+manifestSuffix)
	raw, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		return "", err
	}
	if err := os.WriteFile(p, append(raw, '\n'), 0o644); err != nil {
		return "", err
	}
	return p, nil
}
